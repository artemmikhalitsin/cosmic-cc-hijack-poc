type mapleCipher struct {
	block interface {
		Encrypt(dst, src []byte)
	}
	iv      [4]byte
	version uint16
}

func newMapleCipher(iv []byte, mapleVersion uint16) (*mapleCipher, error) {
	block, err := aes.NewCipher(mapleAESKey)
	if err != nil {
		return nil, err
	}
	c := &mapleCipher{block: block, version: bits.RotateLeft16(mapleVersion, 8)}
	copy(c.iv[:], iv)
	return c, nil
}

func (c *mapleCipher) crypt(data []byte) {
	remaining := len(data)
	start := 0
	chunkLength := 0x5B0
	for remaining > 0 {
		var stream [16]byte
		for i := range stream {
			stream[i] = c.iv[i%4]
		}
		if remaining < chunkLength {
			chunkLength = remaining
		}
		for i := start; i < start+chunkLength; i++ {
			relative := i - start
			if relative%len(stream) == 0 {
				c.block.Encrypt(stream[:], stream[:])
			}
			data[i] ^= stream[relative%len(stream)]
		}
		start += chunkLength
		remaining -= chunkLength
		chunkLength = 0x5B4
	}
	c.updateIV()
}

func (c *mapleCipher) updateIV() {
	c.iv = nextMapleIV(c.iv)
}

func nextMapleIV(old [4]byte) [4]byte {
	out := [4]byte{0xF2, 0x53, 0x50, 0xC6}
	for _, input := range old {
		elina := out[1]
		moritz := mapleIVTable[elina] - input
		out[0] += moritz
		moritz = out[2] ^ mapleIVTable[input]
		elina -= moritz
		out[1] = elina
		elina = out[3]
		moritz = elina
		elina -= out[0]
		moritz = mapleIVTable[moritz] + input
		moritz ^= out[2]
		out[2] = moritz
		elina += mapleIVTable[input]
		out[3] = elina
		rotated := bits.RotateLeft32(binary.LittleEndian.Uint32(out[:]), 3)
		binary.LittleEndian.PutUint32(out[:], rotated)
	}
	return out
}

func (c *mapleCipher) packetHeader(length int) [4]byte {
	ivVersion := uint32(c.iv[3]) | (uint32(c.iv[2]) << 8)
	ivVersion ^= uint32(c.version)
	swappedLength := uint32((length<<8)&0xFF00 | length>>8)
	xored := ivVersion ^ swappedLength
	return [4]byte{byte(ivVersion >> 8), byte(ivVersion), byte(xored >> 8), byte(xored)}
}

func (c *mapleCipher) validHeader(header uint32) bool {
	return byte(header>>24)^c.iv[2] == byte(c.version>>8) &&
		byte(header>>16)^c.iv[3] == byte(c.version)
}

func maplePacketLength(header uint32) int {
	length := (header >> 16) ^ (header & 0xFFFF)
	return int((length<<8)&0xFF00 | (length>>8)&0xFF)
}

func mapleEncryptData(data []byte) {
	for round := 0; round < 6; round++ {
		var remember byte
		dataLength := byte(len(data))
		if round%2 == 0 {
			for i, current := range data {
				current = bits.RotateLeft8(current, 3)
				current += dataLength
				current ^= remember
				remember = current
				current = bits.RotateLeft8(current, -int(dataLength))
				current = ^current + 0x48
				dataLength--
				data[i] = current
			}
		} else {
			for i := len(data) - 1; i >= 0; i-- {
				current := data[i]
				current = bits.RotateLeft8(current, 4)
				current += dataLength
				current ^= remember
				remember = current
				current ^= 0x13
				current = bits.RotateLeft8(current, -3)
				dataLength--
				data[i] = current
			}
		}
	}
}

func mapleDecryptData(data []byte) {
	for round := 1; round <= 6; round++ {
		var remember byte
		dataLength := byte(len(data))
		if round%2 == 0 {
			for i, current := range data {
				current -= 0x48
				current = ^current
				current = bits.RotateLeft8(current, int(dataLength))
				nextRemember := current
				current ^= remember
				remember = nextRemember
				current -= dataLength
				current = bits.RotateLeft8(current, -3)
				dataLength--
				data[i] = current
			}
		} else {
			for i := len(data) - 1; i >= 0; i-- {
				current := data[i]
				current = bits.RotateLeft8(current, 3)
				current ^= 0x13
				nextRemember := current
				current ^= remember
				remember = nextRemember
				current -= dataLength
				current = bits.RotateLeft8(current, -4)
				dataLength--
				data[i] = current
			}
		}
	}
}
